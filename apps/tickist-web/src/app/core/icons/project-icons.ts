export const DEFAULT_PROJECT_ICON: ProjectIconKey = 'folder';

export const PROJECT_ICON_CATEGORIES: readonly ProjectIconCategory[] =
  CATALOGUE.map(([name, entries]) => ({
    name,
    icons: entries.map(([key, label, keywords]) => ({
      key,
      label,
      category: name,
      keywords,
    })),
  }));

export const PROJECT_ICON_OPTIONS: readonly ProjectIconOption[] =
  PROJECT_ICON_CATEGORIES.flatMap((category) => category.icons);

const LABELS = new Map<string, string>(
  PROJECT_ICON_OPTIONS.map((option) => [option.key, option.label])
);

/** Icons whose name, label, category or keywords contain every search word. */
export function searchProjectIcons(query: string): ProjectIconOption[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);

  if (!words.length) return [...PROJECT_ICON_OPTIONS];

  return PROJECT_ICON_OPTIONS.filter((option) => {
    const text =
      `${option.key} ${option.label} ${option.category} ${option.keywords}`.toLowerCase();

    return words.every((word) => text.includes(word));
  });
}

function isProjectIconKey(value: string): value is ProjectIconKey {
  return Object.hasOwn(ICONS_BY_KEY, value);
}

export function resolveProjectIconKey(
  raw: string | null | undefined
): ProjectIconKey {
  const normalized = raw?.trim().toLowerCase() ?? '';

  if (isProjectIconKey(normalized)) {
    return normalized;
  }

  return DEFAULT_PROJECT_ICON;
}

export function resolveProjectIconData(raw: string | null | undefined): string {
  return ICONS_BY_KEY[resolveProjectIconKey(raw)];
}

export function projectIconLabel(raw: string | null | undefined): string {
  return LABELS.get(resolveProjectIconKey(raw)) ?? 'Folder';
}
